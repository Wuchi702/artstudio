import type { Photo, Project } from './projects';

type Frame = readonly [file: string, caption: string, widths: readonly number[]];
type Room = readonly [label: string, frames: readonly Frame[]];

function visualization(slug: string, title: string, featured: boolean, layout: Project['layout'], rooms: readonly Room[]): Project {
  const gallery: Photo[] = rooms.flatMap(([group, frames]) => frames.map(([file, caption, widths]) => ({
    src: `/images/portfolio/${slug}-${file}.webp`,
    alt: `${title} — ${caption}`,
    caption,
    group,
    widths
  })));

  return { id: slug, slug, title, status: 'visualization', featured, layout, cover: gallery[0], gallery, sections: ['gallery'] };
}

